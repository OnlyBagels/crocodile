const ALL = EMOJI_GROUPS.flatMap((g) => g.emoji);

/** Emoji whose names start with (then contain) the query, best first. */
export function searchEmoji(query: string, limit = 8): { emoji: string; name: string }[] {
  const q = query.toLowerCase().replace(/^:/, '');
  if (!q) return [];
  const scored: { emoji: string; name: string; score: number }[] = [];
  for (const [emoji, names] of ALL) {
    const words = names.split(' ');
    const score = words.some((w) => w.startsWith(q))
      ? words[0]!.startsWith(q)
        ? 0
        : 1
      : names.includes(q)
        ? 2
        : -1;
    if (score >= 0) scored.push({ emoji, name: words[0]!, score });
  }
  return scored
    .sort((a, b) => a.score - b.score)
    .slice(0, limit)
    .map(({ emoji, name }) => ({ emoji, name }));
}

/** ":thumbsup:" and the like typed in full become the emoji. */
export function replaceShortcodes(text: string): string {
  return text.replace(/:([a-z0-9_+-]+):/gi, (all, code: string) => {
    const hit = ALL.find(([, names]) => names.split(' ')[0] === code.toLowerCase());
    return hit ? hit[0] : all;
  });
}
